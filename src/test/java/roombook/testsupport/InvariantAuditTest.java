    @Test
    @DisplayName("Приймання 2: На 1 000 чистих рядків усі аудиторські запити повертають порожній результат")
    void cleanOneThousandRowsPassAllAudits() throws SQLException {
        // 1. Створюємо 2 адміністраторів та 8 працівників
        long admin1 = TestDataBuilder.appUser().username("superadmin").role("ADMIN").insert();
        long admin2 = TestDataBuilder.appUser().username("secadmin").role("ADMIN").insert();
        assertTrue(admin1 > 0 && admin2 > 0);

        long[] users = new long[8];
        for (int i = 0; i < 8; i++) {
            users[i] = TestDataBuilder.appUser().username("user_" + i).role("EMPLOYEE").insert();
        }

        // 2. Створюємо 10 кімнат (усі active = true)
        long[] rooms = new long[10];
        for (int i = 0; i < 10; i++) {
            rooms[i] = TestDataBuilder.room().name("Room " + (i + 1)).floor(i % 3 + 1).capacity(10).insert();
        }

        // 3. Генеруємо 1 000 чистих бронювань:
        // 10 кімнат, по 100 бронювань у кожній (10 днів по 10 слотів на день)
        // Кожен слот: 45 хвилин (напр. 09:00-09:45, 09:45-10:30, ...)
        LocalDate baseDate = LocalDate.of(2026, 11, 2);
        int totalBookingsCreated = 0;

        for (int r = 0; r < 10; r++) {
            long roomId = rooms[r];
            int roomBookings = 0;
            for (int day = 0; day < 10; day++) {
                LocalDate date = baseDate.plusDays(day);
                for (int slot = 0; slot < 10; slot++) {
                    LocalTime start = LocalTime.of(9, 0).plusMinutes(slot * 45L);
                    LocalTime end = start.plusMinutes(45);
                    LocalDateTime startAt = LocalDateTime.of(date, start);
                    LocalDateTime endAt = LocalDateTime.of(date, end);
                    long authorId = users[slot % users.length];

                    // Кожне 10-те бронювання зробимо скасованим (CANCELLED з коректними полями)
                    boolean isCancelled = (slot == 9);

                    var builder = TestDataBuilder.booking()
                            .roomId(roomId)
                            .authorId(authorId)
                            .title("Meeting " + r + "-" + day + "-" + slot)
                            .startAt(startAt)
                            .endAt(endAt);

                    if (isCancelled) {
                        builder.status("CANCELLED")
                                .cancelledAt(Instant.now())
                                .cancelledById(admin1);
                    } else {
                        builder.status("ACTIVE");
                    }

                    long id = builder.insert();
                    assertTrue(id > 0);
                    roomBookings++;
                    totalBookingsCreated++;
                }
            }
            assertEquals(100, roomBookings);
        }

        assertEquals(1000, totalBookingsCreated, "Має бути створено рівно 1 000 бронювань");

        // 4. Виконуємо повний аудит від ролі roombook_backup
        assertDoesNotThrow(() -> InvariantAudit.assertAllInvariantsHold(),
                "На 1 000 чистих рядків усі запити обов'язкового аудиту мають повернути порожній результат");

        // 5. Перевіряємо також інформативний запит на чистих даних
        try (Connection backup = PostgresContainerHolder.getBackupConnection()) {
            List<Map<String, Object>> informativeViolations = InvariantAudit.checkInformativeInv02To05(
                    backup, 15, LocalTime.of(9, 0), LocalTime.of(18, 0), 15, 240
            );
            assertTrue(informativeViolations.isEmpty(),
                    "Чисті бронювання повністю відповідають стандартним параметрам робочого дня");
        }
    }

