    private void createUnconstrainedSchema(Connection conn) throws SQLException {
        try (Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE SCHEMA IF NOT EXISTS " + VIOLATIONS_SCHEMA);
            stmt.execute("GRANT USAGE ON SCHEMA " + VIOLATIONS_SCHEMA + " TO roombook_backup");

            // Копії таблиць без жодних обмежень (без PK, FK, CHECK, EXCLUDE, UNIQUE)
            stmt.execute("CREATE TABLE " + VIOLATIONS_SCHEMA + ".room (" +
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY," +
                    "name VARCHAR(100)," +
                    "name_key VARCHAR(200)," +
                    "floor INT," +
                    "capacity INT," +
                    "equipment VARCHAR(500)," +
                    "active BOOLEAN" +
                    ")");

            stmt.execute("CREATE TABLE " + VIOLATIONS_SCHEMA + ".app_user (" +
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY," +
                    "username VARCHAR(64)," +
                    "username_key VARCHAR(64)," +
                    "display_name VARCHAR(100)," +
                    "password_hash VARCHAR(255)," +
                    "role VARCHAR(16)," +
                    "enabled BOOLEAN" +
                    ")");

            stmt.execute("CREATE TABLE " + VIOLATIONS_SCHEMA + ".booking (" +
                    "id BIGINT GENERATED BY DEFAULT AS IDENTITY," +
                    "room_id BIGINT," +
                    "author_id BIGINT," +
                    "title VARCHAR(200)," +
                    "start_at TIMESTAMP," +
                    "end_at TIMESTAMP," +
                    "status VARCHAR(16)," +
                    "created_at TIMESTAMPTZ," +
                    "cancelled_at TIMESTAMPTZ," +
                    "cancelled_by_id BIGINT" +
                    ")");
        }
    }

