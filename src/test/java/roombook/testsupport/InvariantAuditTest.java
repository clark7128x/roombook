                stmt.execute("INSERT INTO " + VIOLATIONS_SCHEMA + ".booking (id, room_id, author_id, title, start_at, end_at, status, created_at) " +
                        "VALUES (103, 1, 1, 'B3', '2026-11-02 12:00', '2026-11-02 13:00', 'ACTIVE', NOW())");

                // Room 2: той самий час 10:00-11:30, але в іншій кімнаті (не перетинається)
                stmt.execute("INSERT INTO " + VIOLATIONS_SCHEMA + ".booking (id, room_id, author_id, title, start_at, end_at, status, created_at) " +
                        "VALUES (104, 2, 1, 'B4', '2026-11-02 10:00', '2026-11-02 11:30', 'ACTIVE', NOW())");

